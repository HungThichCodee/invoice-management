'use strict';
const path = require('node:path');
const { capture, captureAtBottom, captureFullPage } = require('./smokeReady');
const pause = () => new Promise(resolve => setTimeout(resolve, 300));

async function exercise(state, base) {
  const web = state.window.webContents;
  const initial = await web.executeJavaScript("({cards:document.querySelectorAll('.report-overview-card').length,rate:!!document.querySelector('.report-rate'),quarters:document.querySelectorAll('.report-quarters button').length})");
  if (initial.cards !== 5 || !initial.rate || initial.quarters !== 5) throw Error(`Màn báo cáo tháng thiếu thành phần thiết kế: ${JSON.stringify(initial)}`);
  const visibleMonths = await web.executeJavaScript("document.querySelectorAll('.report-table tbody tr').length");
  if (visibleMonths !== new Date().getMonth() + 1) throw Error(`Bảng tháng có ${visibleMonths} kỳ, bao gồm tháng tương lai hoặc thiếu tháng hiện tại.`);
  const full = await captureFullPage(state.window, path.join(base, 'reportsMonthFull.png'));
  if (full.height <= 900) throw Error(`Ảnh toàn trang báo cáo bị cắt: ${JSON.stringify(full)}`);
  await captureAtBottom(state.window, path.join(base, 'reportsMonthBottom.png'));
  const month = new Date().getMonth() + 1;
  const quarterNumber = Math.ceil(month / 3);
  await web.executeJavaScript(`document.querySelector('[data-action="quarter:${quarterNumber}"]').click();true`);
  await pause();
  const quarter = await web.executeJavaScript("document.querySelectorAll('.report-table tbody tr').length");
  if (quarter !== (month - 1) % 3 + 1) throw Error(`Lọc quý trả về ${quarter} dòng, không khớp tháng hiện tại.`);
  const periodKey = new Date().toLocaleDateString('en-CA').slice(0, 7);
  await web.executeJavaScript(`(()=>{const input=document.querySelector('#reportSearch');input.value='${periodKey}';input.dispatchEvent(new Event('change',{bubbles:true}));return true})()`);
  await pause();
  const search = await web.executeJavaScript("document.querySelectorAll('.report-table tbody tr').length");
  if (search !== 1) throw Error(`Tìm tháng trả về ${search} dòng, cần 1.`);
  await web.executeJavaScript(`(()=>{document.querySelector('[data-action="quarter:all"]').click();return true})()`);
  await pause();
  await web.executeJavaScript("(()=>{const input=document.querySelector('#reportSearch');input.value='';input.dispatchEvent(new Event('change',{bubbles:true}));return true})()");
  await pause();
  await web.executeJavaScript("document.querySelector('[data-action=year]').click();true");
  await pause();
  const annual = await web.executeJavaScript("({cards:document.querySelectorAll('.report-overview-card').length,rows:document.querySelectorAll('.report-table tbody tr').length})");
  if (annual.cards !== 4 || annual.rows !== 3) throw Error(`Màn báo cáo năm thiếu dữ liệu: ${JSON.stringify(annual)}`);
  await capture(state.window, path.join(base, 'reportsYear.png'));
  await captureFullPage(state.window, path.join(base, 'reportsYearFull.png'));
  await captureAtBottom(state.window, path.join(base, 'reportsYearBottom.png'));
  await web.executeJavaScript(`document.querySelector('[data-action^="year:"]').click();true`);
  await pause();
  const drilldown = await web.executeJavaScript("({rows:document.querySelectorAll('.report-table tbody tr').length,year:document.querySelector('#year')?.value})");
  if (drilldown.rows !== visibleMonths || drilldown.year !== String(new Date().getFullYear())) throw Error(`Mở chi tiết năm không về báo cáo tháng: ${JSON.stringify(drilldown)}`);
  const period = new Date().toLocaleDateString('en-CA').slice(0, 7);
  const label = await web.executeJavaScript(`document.querySelector('[data-period="${period}"]')?.textContent || ''`);
  if (!label.includes(`Tháng ${new Date().getMonth() + 1}/${new Date().getFullYear()}`)) throw Error(`Kỳ báo cáo chưa việt hóa: ${label}`);
  await web.executeJavaScript(`document.querySelector('[data-period="${period}"]').click();true`);
  await pause();
  await capture(state.window, path.join(base, 'reportDetail.png'));
  await captureFullPage(state.window, path.join(base, 'reportDetailFull.png'));
  await captureAtBottom(state.window, path.join(base, 'reportDetailBottom.png'));
}
module.exports = { exercise };
